#!/bin/sh
# Turns photos in the-majestic/photos/ into the web-sized images the site uses.
#
#   1. Name each photo after its slot, e.g. photos/home-hero.jpg, photos/saal-villa-3.png
#      (every slot has a placeholder in images/placeholders/ with the same name)
#   2. Run:  sh tools/process-photos.sh
#
# Each photo is saved as images/<slot>-800.jpg, -1600.jpg and -2400.jpg (never upscaled),
# plus an .avif copy of each that supporting browsers load instead (about a third of the size).
# Then js/data/photos.js is rewritten to list every processed slot, and the site swaps
# those placeholders for the real photos automatically.
# Uses macOS `sips` (AVIF needs macOS 13+).

set -e
cd "$(dirname "$0")/.."

EXTS="jpg jpeg png heic webp tif tiff JPG JPEG PNG HEIC WEBP TIF TIFF"
SIZES="800 1600 2400"
QUALITY=78
AVIF_QUALITY=55   # below about 50, smooth walls and skies start to band
found=0
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

for placeholder in images/placeholders/*.svg; do
  slot=$(basename "$placeholder" .svg)
  src=""
  for ext in $EXTS; do
    if [ -f "photos/$slot.$ext" ]; then src="photos/$slot.$ext"; break; fi
  done
  [ -z "$src" ] && continue

  width=$(sips -g pixelWidth "$src" | awk '/pixelWidth/ { print $2 }')
  # Old sizes from a previous, larger photo would otherwise linger
  rm -f images/"$slot"-*.jpg images/"$slot"-*.avif
  native=""
  for size in $SIZES; do
    if [ "$width" -lt "$size" ]; then
      # Never upscale: a smaller original is kept once, at its own width
      [ -n "$native" ] && break
      size=$width
      native=1
    fi
    out="images/$slot-$size.jpg"
    if [ "$width" -gt "$size" ]; then
      sips -s format jpeg -s formatOptions "$QUALITY" --resampleWidth "$size" "$src" --out "$out" >/dev/null
    else
      sips -s format jpeg -s formatOptions "$QUALITY" "$src" --out "$out" >/dev/null
    fi
    # Browsers draw AVIFs with an odd width or height as blank, so trim to even sizes first
    w=$(sips -g pixelWidth "$out" | awk '/pixelWidth/ { print $2 }')
    h=$(sips -g pixelHeight "$out" | awk '/pixelHeight/ { print $2 }')
    even="$tmp/$slot-$size.jpg"
    sips -c $((h - h % 2)) $((w - w % 2)) "$out" --out "$even" >/dev/null
    sips -s format avif -s formatOptions "$AVIF_QUALITY" "$even" --out "images/$slot-$size.avif" >/dev/null
  done
  echo "  $slot  <-  $src"
  found=$((found + 1))
done

# List every slot that has processed images (from this run or earlier ones)
{
  echo "/* Generated by tools/process-photos.sh. Do not edit by hand."
  echo "   Each processed slot lists the widths available in images/. */"
  echo "export const PHOTOS = {"
  for placeholder in images/placeholders/*.svg; do
    slot=$(basename "$placeholder" .svg)
    widths=$(ls images/"$slot"-*.jpg 2>/dev/null | sed -E "s|images/$slot-([0-9]+)\.jpg|\1|" | grep -E '^[0-9]+$' | sort -n | tr '\n' ',' | sed 's/,$//')
    [ -n "$widths" ] && echo "  \"$slot\": [$widths],"
  done
  echo "};"
} > js/data/photos.js

if [ "$found" -eq 0 ]; then
  echo "No photos found. Add files such as photos/home-hero.jpg, then run this again."
else
  echo "Processed $found photo(s) into images/ and updated js/data/photos.js."
fi
